#!/usr/bin/env python3
"""Compile only. Regenerate C++ from the preserved Arduino source; never upload."""
from pathlib import Path
import os
import re
import subprocess

ROOT = Path(__file__).resolve().parent.parent
FIRMWARE = ROOT / "firmware"
ORIGINAL = next((ROOT / "RB022_AIRCOPTER_GEAR_TYPE").glob("*/AirCopter"))


def convert(source: str) -> str:
    replacements = {
        "void evaluateCommand();": "void evaluateCommand(uint8_t payloadSize);",
        "evaluateCommand();  // we got a valid packet": "evaluateCommand(dataSize[CURRENTPORT]);  // we got a valid packet",
        "void evaluateCommand() {": "void evaluateCommand(uint8_t payloadSize) {\n  if (!validControlPayload(cmdMSP[CURRENTPORT], payloadSize)) return;\n"
                                    "  if (f.ARMED && writesEeprom(cmdMSP[CURRENTPORT])) return;",
        "   case MSP_SET_RAW_RC_SERIAL:\n": "   case MSP_SET_RAW_RC_SERIAL:\n     serialArmGuard.rcReceived(millis());\n",
        "   case MSP_ARM:\n     go_arm();":
            "   case MSP_ARM:\n     if (serialArmGuard.allows(serialRcValue[THROTTLE], millis(), i2c_errors_count)) go_arm();",
        # immediate stop: legacy go_disarm() blocks 200 ms with motors still driven
        "   case MSP_DISARM:\n     go_disarm();": "   case MSP_DISARM:\n     f.ARMED = 0; flightState &= 0x7f;",
        # first statement, ahead of serialCom()'s early return on a full TX buffer
        "void serialCom() {\n":
            "void serialCom() {\n  if (f.ARMED && serialArmGuard.mustCut(millis(), i2c_errors_count)) { f.ARMED = 0; flightState &= 0x7f; }\n",
        "     serialize16(100); //version": "     serialize16(SerialArmGuard::kFirmwareId); //version",
        "   case MSP_AIR:\n": "   case Optical::kMspOptical:\n     headSerialReply(8);\n     serialize8(Optical::status());\n"
                             "     serialize16(Optical::heightMm());\n     serialize16(Optical::flowX());\n"
                             "     serialize16(Optical::flowY());\n     serialize8(Optical::quality());\n     break;\n"
                             "   case MSP_AIR:\n",
    }
    for old, new in replacements.items():
        if source.count(old) != 1:
            raise ValueError("Original source changed; review conversion: " + old)
        source = source.replace(old, new)
    source = re.sub(r'(?m)^#line (\d+) "[^"\n]+/([^/"\n]+)"$', r'#line \1 "\2"', source)
    return ('// Generated by firmware/build.py; edit the generator, not this file.\n'
            '#include <Arduino.h>\n#include "ControlPayload.hpp"\n#include "ArmGuard.hpp"\n#include "OpticalSensors.hpp"\n'
            'static SerialArmGuard serialArmGuard;\n'
            '#define setup legacySetup\n#define loop legacyLoop\n'
            + source + '\n#undef setup\n#undef loop\n#include "FlightController.hpp"\n'
            'void setup() { FlightController::begin(); }\n'
            'void loop() { FlightController::update(); }\n')


def main():
    cli = ROOT / ".tools/arduino/bin/arduino-cli"
    config = ROOT / ".tools/arduino/arduino-cli.yaml"
    native = Path(os.environ.get("RB022_AVR_BIN", "/tmp/rb022-native-avr/avr-gcc@8/8.5.0_5/bin"))
    ctags = Path(os.environ.get("RB022_CTAGS_BIN", "/tmp/rb022-ctags/bin"))
    env = os.environ.copy()
    env["PATH"] = str(native) + os.pathsep + env["PATH"]
    logs = ROOT / os.environ.get("RB022_FIRMWARE_LOG_DIR", "evidence/2026-10-29")
    logs.mkdir(parents=True, exist_ok=True)
    common = [str(cli), "--config-file", str(config), "compile", "--fqbn", "arduino:avr:leonardo",
              "--warnings", "all", "--build-property", "compiler.path=" + str(native) + "/",
              "--build-property", "runtime.tools.ctags.path=" + str(ctags)]
    for kind in ["cpp", "c", "S", "c.elf"]:
        common += ["--build-property", f"compiler.{kind}.extra_flags=-B{native}/"]

    def compile_sketch(name, sketch):
        build = FIRMWARE / "build" / name
        command = common + ["--build-path", str(build), str(sketch)]
        result = subprocess.run(command, env=env, capture_output=True, text=True)
        (logs / f"firmware-{name}-build.log").write_text(
            "COMMAND: " + repr(command) + "\n" + result.stdout + result.stderr + f"\nEXIT: {result.returncode}\n")
        print(name, result.returncode)
        print("\n".join(line for line in result.stdout.splitlines() if line.startswith(("Sketch uses", "Global variables"))))
        result.check_returncode()
        return build

    original_build = compile_sketch("original-native", ORIGINAL)
    sketch = FIRMWARE / "AirCopterCpp"
    sketch.mkdir(exist_ok=True)
    (sketch / "AirCopterCpp.ino").write_text("// Arduino build marker; entry points live in LegacyFlightController.cpp.\n")
    (sketch / "LegacyFlightController.cpp").write_text(convert((original_build / "sketch/AirCopter.ino.cpp").read_text()))
    for name in ["config.h", "def.h", "tinygps.h"]:
        (sketch / name).write_text(f'#include "{ORIGINAL / name}"\n')
    for name in ["ControlPayload.hpp", "FlightController.hpp", "ArmGuard.hpp", "OpticalSensors.hpp", "OpticalSensors.cpp"]:
        (sketch / name).write_text(f'#include "{FIRMWARE / name}"\n')
    compile_sketch("cpp", sketch)


if __name__ == "__main__":
    main()
